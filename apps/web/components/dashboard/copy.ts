/** Safe lookup for enum maps when the API sends a key the UI does not know yet. */
export function label(map: Record<string, string>, key: string | undefined | null) {
  if (!key) return "—";
  if (map[key]) return map[key];
  const text = key.replaceAll("_", " ");
  return text.charAt(0).toUpperCase() + text.slice(1);
}

